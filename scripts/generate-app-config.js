#!/usr/bin/env node
// Generates src/config/app.ts from environment variables at build time.
// Required env vars: APP_FATHER_NAME, APP_FATHER_EMAIL, APP_FATHER_CALENDAR_ID,
//   APP_MOTHER_NAME, APP_MOTHER_EMAIL, APP_MOTHER_CALENDAR_ID,
//   APP_CHILDREN (comma-separated), APP_START_DATE, APP_FIRST_PARENT

const fs = require("fs")
const path = require("path")

const required = [
  "APP_FATHER_NAME",
  "APP_FATHER_EMAIL",
  "APP_FATHER_CALENDAR_ID",
  "APP_MOTHER_NAME",
  "APP_MOTHER_EMAIL",
  "APP_MOTHER_CALENDAR_ID",
  "APP_CHILDREN",
  "APP_START_DATE",
  "APP_FIRST_PARENT",
]

const missing = required.filter((k) => !process.env[k])
if (missing.length > 0) {
  // If env vars aren't set, skip generation (local dev uses app.ts directly)
  console.log(
    `generate-app-config: skipping (missing env vars: ${missing.join(", ")})`
  )
  process.exit(0)
}

const children = process.env.APP_CHILDREN.split(",").map((s) => s.trim())

const content = `// AUTO-GENERATED by scripts/generate-app-config.js — do not edit manually
export type ParentId = "father" | "mother"

export interface AppConfig {
  parents: Array<{
    id: ParentId
    name: string
    email: string
    calendarId: string
  }>
  children: string[]
  startDate: string
  firstParent: ParentId
}

const config: AppConfig = {
  parents: [
    {
      id: "father",
      name: ${JSON.stringify(process.env.APP_FATHER_NAME)},
      email: ${JSON.stringify(process.env.APP_FATHER_EMAIL)},
      calendarId: ${JSON.stringify(process.env.APP_FATHER_CALENDAR_ID)},
    },
    {
      id: "mother",
      name: ${JSON.stringify(process.env.APP_MOTHER_NAME)},
      email: ${JSON.stringify(process.env.APP_MOTHER_EMAIL)},
      calendarId: ${JSON.stringify(process.env.APP_MOTHER_CALENDAR_ID)},
    },
  ],
  children: ${JSON.stringify(children)},
  startDate: ${JSON.stringify(process.env.APP_START_DATE)},
  firstParent: ${JSON.stringify(process.env.APP_FIRST_PARENT)} as ParentId,
}

export default config
`

const outPath = path.join(__dirname, "../src/config/app.ts")
fs.writeFileSync(outPath, content)
console.log("generate-app-config: wrote src/config/app.ts")
